// frontend/scripts/sync-data-sources.mjs
import { readdir, readFile, writeFile, mkdir, copyFile, rm } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..", "..");
const SRC_DIR = path.join(REPO_ROOT, "docs", "data-sources");
const DST_DIR = path.join(REPO_ROOT, "frontend", "src", "data-sources");
const GEN_FILE = path.join(
  REPO_ROOT,
  "frontend",
  "src",
  "components",
  "sources",
  "SourceRegistry.generated.ts"
);

const REQUIRED_KINDS = ["api", "csv", "seed", "synthesized"];
const REQUIRED_STATUSES = ["verified", "frozen", "unsure"];

function validateStatus(file, fm) {
  if (!fm.verification_status) {
    throw new Error(`${file}: missing 'verification_status' (one of ${REQUIRED_STATUSES.join(", ")})`);
  }
  if (!REQUIRED_STATUSES.includes(fm.verification_status)) {
    throw new Error(
      `${file}: verification_status must be one of ${REQUIRED_STATUSES.join(", ")}, got "${fm.verification_status}"`
    );
  }
  if (fm.verification_status === "unsure") {
    const notes = (fm.verification_notes ?? "").toString().trim();
    if (!notes) {
      throw new Error(
        `${file}: verification_status=unsure requires non-empty 'verification_notes'`
      );
    }
  }
}

function firstParagraph(body) {
  const trimmed = body.trim();
  // Skip the first heading line ("## Vad det är") and grab the next paragraph.
  const lines = trimmed.split("\n");
  let i = 0;
  while (i < lines.length && (lines[i].startsWith("#") || lines[i].trim() === "")) i++;
  let para = "";
  while (i < lines.length && lines[i].trim() !== "") {
    para += (para ? " " : "") + lines[i].trim();
    i++;
  }
  return para.replace(/\s+/g, " ").trim();
}

async function main() {
  if (!existsSync(SRC_DIR)) {
    // Inside Docker build the repo root isn't in the build context — only
    // frontend/. CI runs this script explicitly before `docker build` so the
    // pre-synced files end up inside the context. When the script then runs
    // again from `prebuild` inside the container, just skip silently and
    // trust the pre-synced state.
    console.log(
      `sync-data-sources: source dir not found (${SRC_DIR}); assuming pre-synced — skipping.`
    );
    return;
  }

  // Ensure destination exists, then remove only stale .md files so
  // deletions in docs/ are reflected. Preserve .gitkeep and other
  // non-.md files in the directory.
  await mkdir(DST_DIR, { recursive: true });
  for (const f of await readdir(DST_DIR)) {
    if (f.endsWith(".md")) {
      await rm(path.join(DST_DIR, f), { force: true });
    }
  }

  const files = (await readdir(SRC_DIR))
    .filter((f) => f.endsWith(".md") && !f.startsWith("_") && f !== "INDEX.md")
    .sort();

  if (files.length === 0) {
    throw new Error(`No source MD files in ${SRC_DIR}`);
  }

  const entries = [];

  for (const file of files) {
    const srcPath = path.join(SRC_DIR, file);
    const dstPath = path.join(DST_DIR, file);
    const raw = await readFile(srcPath, "utf8");
    const parsed = matter(raw);
    const fm = parsed.data;

    if (!fm.id) throw new Error(`${file}: missing frontmatter 'id'`);
    if (fm.id !== path.basename(file, ".md")) {
      throw new Error(`${file}: id "${fm.id}" must match filename`);
    }
    if (!fm.name) throw new Error(`${file}: missing 'name'`);
    if (!REQUIRED_KINDS.includes(fm.kind)) {
      throw new Error(`${file}: kind must be one of ${REQUIRED_KINDS.join(", ")}, got "${fm.kind}"`);
    }
    if (!fm.last_verified) throw new Error(`${file}: missing 'last_verified'`);
    validateStatus(file, fm);

    await copyFile(srcPath, dstPath);

    entries.push({
      id: fm.id,
      name: fm.name,
      kind: fm.kind,
      upstream: fm.upstream && fm.upstream !== "~" ? fm.upstream : null,
      license: fm.license ?? null,
      freshness: fm.freshness ?? null,
      lastVerified: String(fm.last_verified),
      blurb: firstParagraph(parsed.content),
      verificationStatus: fm.verification_status,
      verificationNotes: fm.verification_notes
        ? String(fm.verification_notes).trim()
        : null,
    });
  }

  const banner = "// AUTOGENERATED by frontend/scripts/sync-data-sources.mjs — do not edit.\n";
  const body =
    `import type { SourceEntry } from "./SourceRegistry";\n\n` +
    `export const SOURCES: Record<string, SourceEntry> = {\n` +
    entries
      .map(
        (e) =>
          `  ${JSON.stringify(e.id)}: ${JSON.stringify(e, null, 2)
            .split("\n")
            .map((l, i) => (i === 0 ? l : "  " + l))
            .join("\n")},`
      )
      .join("\n") +
    `\n};\n\n` +
    `export type SourceId = keyof typeof SOURCES;\n`;

  await writeFile(GEN_FILE, banner + body);
  console.log(`sync-data-sources: ${entries.length} sources → ${path.relative(REPO_ROOT, GEN_FILE)}`);
}

main().catch((err) => {
  console.error("sync-data-sources failed:", err.message);
  process.exit(1);
});
